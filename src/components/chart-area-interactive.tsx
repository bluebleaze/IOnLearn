const chartConfig = {
  visitors: {
    label: "Visitors",
  },
  desktop: {
    label: "Study streak",
    color: "#6366f1",
  },
  mobile: {
    label: "Focus time",
    color: "#8b5cf6",
  },
} satisfies ChartConfig

export function ChartAreaInteractive() {
  const isMobile = useIsMobile()
  const [timeRange, setTimeRange] = React.useState("90d")

  React.useEffect(() => {
    if (isMobile) {
      setTimeRange("7d")
    }
  }, [isMobile])

  const filteredData = chartData.filter((item) => {
    const date = new Date(item.date)
    const referenceDate = new Date("2024-06-30")
    let daysToSubtract = 90
    if (timeRange === "30d") {
      daysToSubtract = 30
    } else if (timeRange === "7d") {
      daysToSubtract = 7
    }
    const startDate = new Date(referenceDate)
    startDate.setDate(startDate.getDate() - daysToSubtract)
    return date >= startDate
  })

  return (
    <Card className="@container/card overflow-hidden rounded-[28px] border border-indigo-100 bg-[linear-gradient(180deg,_rgba(255,255,255,0.92),_rgba(248,250,255,0.9))] shadow-[0_22px_50px_rgba(79,70,229,0.10)] backdrop-blur-sm dark:border-indigo-500/10 dark:bg-[linear-gradient(180deg,_rgba(15,23,42,0.96),_rgba(17,24,39,0.9))] dark:shadow-[0_22px_50px_rgba(2,6,23,0.58)]">
      <div className="h-1 w-full bg-[linear-gradient(90deg,_#6366f1,_#8b5cf6,_#38bdf8)]" />
      <CardHeader className="px-5 pb-0 pt-5 sm:px-6">
        <div className="flex items-start justify-between gap-3">
          <div>
            <CardTitle className="text-xl font-semibold text-slate-900 dark:text-slate-50">Study momentum</CardTitle>
            <CardDescription className="mt-1 text-slate-500 dark:text-slate-400">
              <span className="hidden @[540px]/card:block">Total focus time for the last 3 months</span>
              <span className="@[540px]/card:hidden">Last 3 months</span>
            </CardDescription>
          </div>
          <div className="rounded-full border border-indigo-200 bg-[linear-gradient(135deg,_rgba(99,102,241,0.12),_rgba(56,189,248,0.08))] px-2.5 py-1 text-[10px] font-semibold uppercase tracking-[0.14em] text-indigo-700 dark:border-indigo-400/30 dark:bg-[linear-gradient(135deg,_rgba(99,102,241,0.18),_rgba(14,165,233,0.08))] dark:text-indigo-200">
            +24.8%
          </div>
        </div>
        <CardAction>
          <ToggleGroup
            type="single"
            value={timeRange}
            onValueChange={setTimeRange}
            variant="outline"
            className="hidden rounded-full border-slate-200 bg-slate-50 *:data-[slot=toggle-group-item]:rounded-full *:data-[slot=toggle-group-item]:px-3 *:data-[slot=toggle-group-item]:py-1.5 *:data-[slot=toggle-group-item]:text-xs @[767px]/card:flex dark:border-white/10 dark:bg-slate-800"
          >
            <ToggleGroupItem value="90d">3 months</ToggleGroupItem>
            <ToggleGroupItem value="30d">30 days</ToggleGroupItem>
            <ToggleGroupItem value="7d">7 days</ToggleGroupItem>
          </ToggleGroup>
          <Select value={timeRange} onValueChange={setTimeRange}>
            <SelectTrigger
              className="flex w-40 rounded-xl border-slate-200 bg-slate-50 text-slate-700 shadow-sm @[767px]/card:hidden dark:border-white/10 dark:bg-slate-800 dark:text-slate-200"
              size="sm"
              aria-label="Select a value"
            >
              <SelectValue placeholder="3 months" />
            </SelectTrigger>
            <SelectContent className="rounded-xl">
              <SelectItem value="90d" className="rounded-lg">3 months</SelectItem>
              <SelectItem value="30d" className="rounded-lg">30 days</SelectItem>
              <SelectItem value="7d" className="rounded-lg">7 days</SelectItem>
            </SelectContent>
          </Select>
        </CardAction>
      </CardHeader>
      <CardContent className="px-2 pb-4 pt-4 sm:px-6 sm:pb-6">
        <ChartContainer
          config={chartConfig}
          className="aspect-auto h-[250px] w-full"
        >
          <AreaChart data={filteredData}>
            <defs>
              <linearGradient id="fillDesktop" x1="0" y1="0" x2="0" y2="1">
                <stop
                  offset="5%"
                  stopColor="#6366f1"
                  stopOpacity={0.32}
                />
                <stop
                  offset="95%"
                  stopColor="#6366f1"
                  stopOpacity={0.04}
                />
              </linearGradient>
              <linearGradient id="fillMobile" x1="0" y1="0" x2="0" y2="1">
                <stop
                  offset="5%"
                  stopColor="#8b5cf6"
                  stopOpacity={0.28}
                />
                <stop
                  offset="95%"
                  stopColor="#8b5cf6"
                  stopOpacity={0.04}
                />
              </linearGradient>
            </defs>
            <CartesianGrid vertical={false} stroke="currentColor" strokeOpacity={0.12} />
            <XAxis
              dataKey="date"
              tickLine={false}
              axisLine={false}
              tickMargin={8}
              minTickGap={32}
              tickFormatter={(value) => {
                const date = new Date(value)
                return date.toLocaleDateString("en-US", {
                  month: "short",
                  day: "numeric",
                })
              }}
              className="fill-slate-500 dark:fill-slate-400"
            />
            <ChartTooltip
              cursor={false}
              content={
                <ChartTooltipContent
                  labelFormatter={(value) => {
                    return new Date(value).toLocaleDateString("en-US", {
                      month: "short",
                      day: "numeric",
                    })
                  }}
                  indicator="dot"
                />
              }
            />
            <Area
              dataKey="mobile"
              type="natural"
              fill="url(#fillMobile)"
              stroke="#8b5cf6"
              strokeWidth={2.5}
              stackId="a"
            />
            <Area
              dataKey="desktop"
              type="natural"
              fill="url(#fillDesktop)"
              stroke="#6366f1"
              strokeWidth={2.5}
              stackId="a"
            />
          </AreaChart>
        </ChartContainer>
      </CardContent>
    </Card>
  )
}
